-- Inicialización del esquema de la práctica, sin datos de ejemplo.
-- La imagen oficial lo ejecuta únicamente al inicializar un directorio de datos vacío.
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE direcciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calle VARCHAR(255),
    ciudad VARCHAR(255),
    codigo_postal VARCHAR(255)
);
CREATE TABLE etiquetas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255)
);
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL,
    direccion_id BIGINT UNIQUE REFERENCES direcciones(id)
);
CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    precio NUMERIC(12,2),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id)
);
CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    total NUMERIC(12,2) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id)
);
CREATE TABLE lineas_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INTEGER,
    precio_unitario NUMERIC(12,2),
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id)
);
CREATE TABLE producto_etiquetas (
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    etiqueta_id BIGINT NOT NULL REFERENCES etiquetas(id),
    PRIMARY KEY (producto_id, etiqueta_id)
);
